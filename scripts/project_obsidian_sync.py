#!/usr/bin/env python3
"""Safely mirror selected project files into an Obsidian vault.

The project copy is the canonical source.  The Obsidian folder is a one-way,
hash-checked reading copy.  A manifest is deliberately a white-list: files
which are not listed are never touched by this program.

This module only uses the Python 3.9 standard library so that it can be used
from a project without installing a separate runtime or package.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import tempfile
from collections import OrderedDict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple


STATE_FILENAME = ".obsidian-sync-state.json"
DEFAULT_INDEX_TARGET = Path("00.專案總入口") / "00.專案總入口.md"
DEFAULT_INDEX_TITLE = "專案總入口"
# Backwards-compatible name used by the ItemGeneration implementation.
INDEX_RELATIVE_PATH = DEFAULT_INDEX_TARGET
MANIFEST_FILENAME = "obsidian_sync_manifest.json"


class ConfigError(ValueError):
    """Raised when a manifest or filesystem boundary is invalid."""


@dataclass
class SyncSummary:
    """Stable, JSON-serialisable result of a check or sync operation."""

    synced: List[str] = field(default_factory=list)
    unchanged: List[str] = field(default_factory=list)
    pending: List[str] = field(default_factory=list)
    conflicts: List[str] = field(default_factory=list)
    missing: List[str] = field(default_factory=list)
    # The managed index is metadata generated by the engine rather than a
    # manifest entry.  Keep its status separate so callers that consumed the
    # original ItemGeneration summary still see only allow-listed files in
    # synced/unchanged/pending, while index conflicts remain visible in the
    # general conflicts list for a clear stop signal.
    index_synced: List[str] = field(default_factory=list)
    index_unchanged: List[str] = field(default_factory=list)
    index_pending: List[str] = field(default_factory=list)
    index_conflicts: List[str] = field(default_factory=list)

    @property
    def clean(self) -> bool:
        return (
            not self.pending
            and not self.conflicts
            and not self.missing
            and not self.index_pending
            and not self.index_conflicts
        )

    @property
    def ok(self) -> bool:
        """Compatibility alias used by the original ItemGeneration script."""

        return self.clean

    def to_dict(self, *, apply: bool) -> Dict[str, Any]:
        return {
            "mode": "sync" if apply else "check",
            "synced": list(self.synced),
            "unchanged": list(self.unchanged),
            "pending": list(self.pending),
            "conflicts": list(self.conflicts),
            "missing": list(self.missing),
            "index": {
                "synced": list(self.index_synced),
                "unchanged": list(self.index_unchanged),
                "pending": list(self.index_pending),
                "conflicts": list(self.index_conflicts),
            },
            "counts": {
                "synced": len(self.synced),
                "unchanged": len(self.unchanged),
                "pending": len(self.pending),
                "conflicts": len(self.conflicts),
                "missing": len(self.missing),
                "index_synced": len(self.index_synced),
                "index_unchanged": len(self.index_unchanged),
                "index_pending": len(self.index_pending),
                "index_conflicts": len(self.index_conflicts),
            },
        }


@dataclass
class ResolvedEntry:
    root: str
    source: str
    target: str
    label: str
    category: str
    allow_sensitive: bool
    source_path: Path
    destination_path: Path


def _inside(child: Path, parent: Path) -> bool:
    """Return whether *child* is in *parent* (including equality)."""

    try:
        child.relative_to(parent)
        return True
    except ValueError:
        return False


def sha256(path: Path) -> str:
    """Return a streaming SHA-256 digest for a regular file."""

    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _atomic_copy(source: Path, destination: Path) -> None:
    """Copy a file through a sibling temporary file and ``os.replace``."""

    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary: Optional[Path] = None
    try:
        with tempfile.NamedTemporaryFile(
            prefix="." + destination.name + ".",
            dir=str(destination.parent),
            delete=False,
        ) as handle:
            temporary = Path(handle.name)
        shutil.copy2(str(source), str(temporary))
        os.replace(str(temporary), str(destination))
        temporary = None
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def _atomic_write_text(destination: Path, content: str) -> None:
    """Atomically write UTF-8 text, creating only the requested parent."""

    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary: Optional[Path] = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="",
            prefix="." + destination.name + ".",
            dir=str(destination.parent),
            delete=False,
        ) as handle:
            handle.write(content)
            temporary = Path(handle.name)
        os.replace(str(temporary), str(destination))
        temporary = None
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def _atomic_write_json_if_changed(destination: Path, value: Dict[str, Any]) -> bool:
    """Write JSON only when the represented state actually differs.

    Comparing parsed values (when possible) means a harmless whitespace or
    key-order difference does not replace the state file merely to reformat
    it; this keeps the atomic-write/no-op guarantee about state, not styling.
    """

    content = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    if destination.is_file():
        with destination.open("r", encoding="utf-8", newline="") as handle:
            existing_content = handle.read()
        if existing_content == content:
            return False
        try:
            if json.loads(existing_content) == value:
                return False
        except json.JSONDecodeError:
            pass
    _atomic_write_text(destination, content)
    return True


def _read_json(path: Path, description: str) -> Dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as handle:
            value = json.load(handle)
    except FileNotFoundError as exc:
        raise ConfigError(f"找不到{description}：{path}") from exc
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ConfigError(f"無法讀取{description}：{path}") from exc
    if not isinstance(value, dict):
        raise ConfigError(f"{description}必須是 JSON 物件：{path}")
    return value


def load_manifest(path: Path) -> Dict[str, Any]:
    """Load and validate manifest-level fields without touching Obsidian."""

    path = Path(path).expanduser().resolve()
    manifest = _read_json(path, "manifest")
    required = {
        "version",
        "project_name",
        "vault_root",
        "target_root",
        "roots",
        "entries",
    }
    missing = required.difference(manifest)
    if missing:
        raise ConfigError(f"manifest 缺少欄位：{', '.join(sorted(missing))}")
    if manifest.get("version") != 1:
        raise ConfigError("目前只支援 manifest version 1")
    if not isinstance(manifest.get("project_name"), str) or not manifest["project_name"].strip():
        raise ConfigError("manifest 的 project_name 必須是非空字串")
    if "\n" in manifest["project_name"] or "\r" in manifest["project_name"]:
        raise ConfigError("manifest 的 project_name 不可含換行")
    if not isinstance(manifest.get("roots"), dict) or not manifest["roots"]:
        raise ConfigError("manifest 的 roots 必須是非空物件")
    if not isinstance(manifest.get("entries"), list):
        raise ConfigError("manifest 的 entries 必須是陣列")
    return manifest


def _load_state(target_root: Path) -> Dict[str, Any]:
    path = target_root / STATE_FILENAME
    if path.is_symlink():
        raise ConfigError(f"同步狀態不可使用 symbolic link：{path}")
    if not path.exists():
        return {"version": 1, "entries": {}}
    if not path.is_file():
        raise ConfigError(f"同步狀態不是檔案：{path}")
    state = _read_json(path, "同步狀態")
    if state.get("version", 1) != 1:
        raise ConfigError(f"同步狀態版本不支援：{path}")
    if not isinstance(state.get("entries"), dict):
        raise ConfigError(f"同步狀態格式錯誤（entries）：{path}")
    if "index" in state and not isinstance(state["index"], dict):
        raise ConfigError(f"同步狀態格式錯誤（index）：{path}")
    return state


def _as_path(value: Any, field_name: str) -> Path:
    if not isinstance(value, str) or not value.strip():
        raise ConfigError(f"{field_name} 必須是非空字串路徑")
    try:
        return Path(value).expanduser()
    except (TypeError, ValueError) as exc:
        raise ConfigError(f"{field_name} 不是有效路徑：{value!r}") from exc


def _resolved_path(value: Any, field_name: str, *, base_dir: Optional[Path] = None) -> Path:
    path = _as_path(value, field_name)
    if base_dir is not None and not path.is_absolute():
        path = base_dir / path
    try:
        return path.resolve()
    except (OSError, RuntimeError) as exc:
        raise ConfigError(f"無法解析{field_name}：{path}") from exc


def _validate_vault_and_target(
    manifest: Dict[str, Any], *, base_dir: Optional[Path] = None
) -> Tuple[Path, Path]:
    vault_root = _resolved_path(manifest["vault_root"], "vault_root", base_dir=base_dir)
    target_root = _resolved_path(manifest["target_root"], "target_root", base_dir=base_dir)
    if not vault_root.is_dir():
        raise ConfigError(f"vault_root 不存在或不是資料夾：{vault_root}")
    if not (vault_root / ".obsidian").is_dir():
        raise ConfigError(f"不是可確認的 Obsidian Vault（缺少 .obsidian）：{vault_root}")
    if not _inside(target_root, vault_root):
        raise ConfigError(f"同步目標不在指定 Vault 內：{target_root}")
    if target_root.exists() and not target_root.is_dir():
        raise ConfigError(f"target_root 存在但不是資料夾：{target_root}")
    return vault_root, target_root


_SENSITIVE_BASENAMES = {
    "cookies.txt",
    "cookie.txt",
    "keycode.txt",
    "id_rsa",
    "id_dsa",
    "id_ecdsa",
    "id_ed25519",
    "db",
    "database",
}
_SENSITIVE_EXTENSIONS = {
    ".pem",
    ".key",
    ".p12",
    ".pfx",
    ".jks",
    ".keystore",
    ".der",
    ".db",
    ".sqlite",
    ".sqlite3",
    ".sqlite-wal",
    ".sqlite-shm",
    ".sqlite3-wal",
    ".sqlite3-shm",
}
_SENSITIVE_COMPONENTS = {
    "secret",
    "secrets",
    "private",
    "private_key",
    "private-keys",
    "credentials",
    "db",
    "database",
}


def _is_sensitive(path: Path, relative_path: Optional[Path] = None) -> bool:
    """Conservatively identify credentials and local state files.

    ``relative_path`` is used for directory-name checks so an operating
    system prefix such as macOS' ``/private`` does not make every temporary
    fixture look sensitive.
    """

    lower_name = path.name.lower()
    if lower_name == ".env" or lower_name.startswith(".env."):
        return True
    if lower_name in _SENSITIVE_BASENAMES:
        return True
    if lower_name.startswith("db.") or lower_name.startswith("database."):
        return True
    if Path(lower_name).suffix in _SENSITIVE_EXTENSIONS:
        return True
    if "keystore" in lower_name or "private_key" in lower_name or "private-key" in lower_name:
        return True
    name_tokens = lower_name.replace("-", ".").replace("_", ".").split(".")
    if any(
        token in {"secret", "secrets", "credential", "credentials", "password"}
        for token in name_tokens
    ):
        return True
    # A file named ``server-private.pem`` is already covered by its suffix;
    # this also catches extension-less private keys without rejecting ordinary
    # documentation that merely mentions the word "private".
    if "private" in lower_name and "key" in lower_name:
        return True
    parts = relative_path.parts if relative_path is not None else path.parts
    return any(part.lower() in _SENSITIVE_COMPONENTS for part in parts)


def _validate_text_field(raw: Dict[str, Any], field_name: str, *, allow_empty: bool = False) -> str:
    value = raw.get(field_name)
    if not isinstance(value, str) or (not allow_empty and not value.strip()):
        raise ConfigError(f"entry 的 {field_name} 必須是非空字串")
    if "\n" in value or "\r" in value:
        raise ConfigError(f"entry 的 {field_name} 不可含換行")
    return value


def _resolve_entries(
    manifest: Dict[str, Any], target_root: Path, *, base_dir: Optional[Path] = None
) -> List[ResolvedEntry]:
    roots: Dict[str, Path] = {}
    for name, value in manifest["roots"].items():
        if not isinstance(name, str) or not name.strip():
            raise ConfigError("roots 的名稱必須是非空字串")
        if "\n" in name or "\r" in name:
            raise ConfigError("roots 的名稱不可含換行")
        root = _resolved_path(value, f"roots.{name}", base_dir=base_dir)
        if not root.is_dir():
            raise ConfigError(f"來源根目錄不存在或不是資料夾：{root}")
        if _inside(target_root, root) or _inside(root, target_root):
            raise ConfigError(
                "來源根目錄與 Obsidian 同步區不可互相包含："
                f"source_root={root}，target_root={target_root}"
            )
        roots[name] = root

    resolved: List[ResolvedEntry] = []
    seen_targets: set[str] = set()
    for index, raw in enumerate(manifest["entries"]):
        if not isinstance(raw, dict):
            raise ConfigError(f"entries[{index}] 必須是物件")
        root_name = raw.get("root")
        if not isinstance(root_name, str) or root_name not in roots:
            raise ConfigError(f"未知來源根目錄：{root_name!r}")
        source_rel = _as_path(raw.get("source"), f"entries[{index}].source")
        target_rel = _as_path(raw.get("target"), f"entries[{index}].target")
        source_lexical = roots[root_name] / source_rel
        destination_lexical = target_root / target_rel
        try:
            source = source_lexical.resolve()
            destination_resolved = destination_lexical.resolve()
        except (OSError, RuntimeError) as exc:
            raise ConfigError(f"無法解析 entries[{index}] 路徑") from exc
        if not _inside(source, roots[root_name]):
            raise ConfigError(f"來源超出根目錄：{source}")
        if not _inside(destination_resolved, target_root):
            raise ConfigError(f"目標超出 Obsidian 同步區：{destination_resolved}")
        try:
            # Use the resolved (normalised) path for identity so ``a/../b``
            # cannot bypass duplicate-target detection.  Keep the lexical
            # path separately for replacing an in-vault symlink itself.
            relative_target = destination_resolved.relative_to(target_root).as_posix()
        except ValueError as exc:
            raise ConfigError(f"目標超出 Obsidian 同步區：{destination_lexical}") from exc
        if relative_target in ("", "."):
            raise ConfigError("同步 target 必須是檔案路徑")
        if relative_target == STATE_FILENAME:
            raise ConfigError(f"同步 target 保留給狀態檔，不可使用：{relative_target}")
        if relative_target in seen_targets:
            raise ConfigError(f"重複的同步目標：{relative_target}")
        seen_targets.add(relative_target)

        label = _validate_text_field(raw, "label")
        category = _validate_text_field(raw, "category")
        allow_sensitive = raw.get("allow_sensitive", False)
        if not isinstance(allow_sensitive, bool):
            raise ConfigError(f"entries[{index}].allow_sensitive 必須是布林值")
        if _is_sensitive(source, source_rel) and not allow_sensitive:
            raise ConfigError(f"來源看起來含敏感資料，需明確 allow_sensitive=true：{source}")
        resolved.append(
            ResolvedEntry(
                root=root_name,
                source=str(source_rel),
                target=relative_target,
                label=label,
                category=category,
                allow_sensitive=allow_sensitive,
                source_path=source,
                destination_path=destination_lexical,
            )
        )
    return resolved


def _resolve_index(
    manifest: Dict[str, Any], target_root: Path, entry_targets: Iterable[str]
) -> Tuple[str, str, Path]:
    default_title = f"{manifest['project_name']} 專案總入口"
    raw = manifest.get("index")
    if raw is None:
        target_rel = DEFAULT_INDEX_TARGET
        title = default_title
    else:
        if not isinstance(raw, dict):
            raise ConfigError("manifest 的 index 必須是物件")
        target_rel = _as_path(raw.get("target", DEFAULT_INDEX_TARGET.as_posix()), "index.target")
        title = raw.get("title", default_title)
        if not isinstance(title, str) or not title.strip():
            raise ConfigError("index.title 必須是非空字串")
        if "\n" in title or "\r" in title:
            raise ConfigError("index.title 不可含換行")
    destination_lexical = target_root / target_rel
    try:
        destination_resolved = destination_lexical.resolve()
    except (OSError, RuntimeError) as exc:
        raise ConfigError("無法解析 index.target") from exc
    if not _inside(destination_resolved, target_root):
        raise ConfigError(f"入口頁目標超出 Obsidian 同步區：{destination_resolved}")
    relative_target = destination_resolved.relative_to(target_root).as_posix()
    if relative_target in ("", "."):
        raise ConfigError("index.target 必須是檔案路徑")
    if relative_target == STATE_FILENAME:
        raise ConfigError(f"入口頁 target 保留給狀態檔，不可使用：{relative_target}")
    if relative_target in set(entry_targets):
        raise ConfigError(f"入口頁與 entries 重複的同步目標：{relative_target}")
    return relative_target, title, destination_lexical


def _relative_wikilink(entry_target: str, index_target: str) -> str:
    index_parent = Path(index_target).parent
    try:
        relative = os.path.relpath(entry_target, start=str(index_parent))
    except ValueError:
        relative = entry_target
    return Path(relative).as_posix()


def _render_index(entries: Sequence[ResolvedEntry], index_target: str, title: str, project_name: str) -> str:
    groups: "OrderedDict[str, List[ResolvedEntry]]" = OrderedDict()
    for entry in entries:
        groups.setdefault(entry.category, []).append(entry)
    lines = [f"# {title}", "", f"專案：{project_name}", ""]
    if not entries:
        lines.append("目前沒有列入同步的文件。")
    for category, category_entries in groups.items():
        lines.extend([f"## {category}", ""])
        for entry in sorted(category_entries, key=lambda item: (item.label, item.target)):
            link = _relative_wikilink(entry.target, index_target)
            lines.append(f"- [[{link}|{entry.label}]]")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _state_entry(source: Path, digest: str) -> Dict[str, str]:
    return {
        "source": str(source),
        "source_sha256": digest,
        "destination_sha256": digest,
    }


def _state_for(
    manifest: Dict[str, Any],
    manifest_path: Path,
    entries: Dict[str, Dict[str, str]],
    index_target: str,
    index_digest: str,
) -> Dict[str, Any]:
    return {
        "version": 1,
        "project_name": manifest["project_name"],
        "manifest_path": str(manifest_path),
        "entries": entries,
        "index": {"target": index_target, "sha256": index_digest},
    }


def _validate_state_identity(
    state: Dict[str, Any], manifest: Dict[str, Any], manifest_path: Path, target_root: Path
) -> None:
    """Prevent one Obsidian target from being adopted by another manifest."""

    recorded_name = state.get("project_name")
    recorded_manifest = state.get("manifest_path")
    if recorded_name != manifest["project_name"] or recorded_manifest != str(manifest_path):
        raise ConfigError(
            "Obsidian 同步目標已綁定另一個專案或 manifest；不得自動接管："
            f"target_root={target_root}，recorded_project={recorded_name!r}，"
            f"recorded_manifest={recorded_manifest!r}"
        )


def run_sync(manifest_path: Path, *, apply: bool) -> SyncSummary:
    """Check or apply a manifest in one all-or-nothing preflight batch.

    ``apply=False`` is strictly read-only.  For ``apply=True`` all source,
    destination, state and index decisions are made before the first copy; a
    conflict or missing source therefore prevents every copy in that run.
    """

    manifest_path = Path(manifest_path).expanduser().resolve()
    manifest = load_manifest(manifest_path)
    manifest_dir = manifest_path.parent
    _vault_root, target_root = _validate_vault_and_target(manifest, base_dir=manifest_dir)
    entries = _resolve_entries(manifest, target_root, base_dir=manifest_dir)
    index_target, index_title, index_path = _resolve_index(
        manifest, target_root, (entry.target for entry in entries)
    )
    state = _load_state(target_root)
    if (target_root / STATE_FILENAME).is_file():
        _validate_state_identity(state, manifest, manifest_path, target_root)
    previous_entries = state.get("entries", {})
    previous_index = state.get("index", {})
    previous_index_digest = (
        previous_index.get("sha256")
        if isinstance(previous_index, dict) and previous_index.get("target") == index_target
        else None
    )

    summary = SyncSummary()
    next_entries: Dict[str, Dict[str, str]] = {}
    copy_actions: List[Tuple[Path, Path, str, str]] = []

    for entry in entries:
        source = entry.source_path
        destination = entry.destination_path
        key = entry.target
        if not source.is_file():
            summary.missing.append(f"{key} <- {source}")
            continue
        if destination.exists() and not destination.is_file():
            raise ConfigError(f"同步目標不是檔案：{destination}")
        if destination.is_file():
            try:
                if os.path.samefile(str(source), str(destination)):
                    raise ConfigError(f"來源與同步目標不可是同一檔案：{source}")
            except FileNotFoundError:
                # A concurrent deletion is handled by the normal hash/missing
                # path below; it is not a reason to follow an external link.
                pass
        source_digest = sha256(source)
        destination_digest = sha256(destination) if destination.is_file() else None
        previous = previous_entries.get(key, {})
        previous_destination_digest = (
            previous.get("destination_sha256") if isinstance(previous, dict) else None
        )

        if destination_digest == source_digest:
            summary.unchanged.append(key)
            next_entries[key] = _state_entry(source, source_digest)
        elif destination_digest is None:
            if not apply:
                summary.pending.append(key)
            copy_actions.append((source, destination, key, source_digest))
        elif previous_destination_digest == destination_digest:
            if not apply:
                summary.pending.append(key)
            copy_actions.append((source, destination, key, source_digest))
        else:
            summary.conflicts.append(key)

    index_content = _render_index(entries, index_target, index_title, manifest["project_name"])
    index_digest = hashlib.sha256(index_content.encode("utf-8")).hexdigest()
    if index_path.exists() and not index_path.is_file():
        raise ConfigError(f"入口頁目標不是檔案：{index_path}")
    current_index_digest = sha256(index_path) if index_path.is_file() else None
    if current_index_digest == index_digest:
        summary.index_unchanged.append(index_target)
    elif current_index_digest is None:
        if not apply:
            summary.index_pending.append(index_target)
    elif previous_index_digest == current_index_digest:
        if not apply:
            summary.index_pending.append(index_target)
    else:
        summary.index_conflicts.append(index_target)
        summary.conflicts.append(index_target)

    # This is the all-entry preflight gate.  No copy, index write or state
    # write is allowed when any source is missing or any destination conflicts.
    if summary.conflicts or summary.missing:
        return summary
    index_needs_copy = current_index_digest != index_digest
    if not apply:
        return summary

    for source, destination, key, source_digest in copy_actions:
        _atomic_copy(source, destination)
        if sha256(destination) != source_digest:
            raise RuntimeError(f"同步後雜湊不一致：{destination}")
        summary.synced.append(key)
        next_entries[key] = _state_entry(source, source_digest)

    if index_needs_copy:
        _atomic_write_text(index_path, index_content)
        if sha256(index_path) != index_digest:
            raise RuntimeError(f"入口頁寫入後雜湊不一致：{index_path}")
        summary.index_synced.append(index_target)

    next_state = _state_for(manifest, manifest_path, next_entries, index_target, index_digest)
    _atomic_write_json_if_changed(target_root / STATE_FILENAME, next_state)
    return summary


def _print_summary(summary: SyncSummary, *, apply: bool, as_json: bool = False) -> None:
    if as_json:
        print(json.dumps(summary.to_dict(apply=apply), ensure_ascii=False, indent=2))
        return
    print(f"模式：{'同步' if apply else '檢查'}")
    print(f"已同步：{len(summary.synced)}")
    print(f"無變更：{len(summary.unchanged)}")
    print(f"待同步：{len(summary.pending)}")
    print(f"衝突：{len(summary.conflicts)}")
    print(f"來源缺少：{len(summary.missing)}")
    print(f"入口頁已同步：{len(summary.index_synced)}")
    print(f"入口頁無變更：{len(summary.index_unchanged)}")
    print(f"入口頁待同步：{len(summary.index_pending)}")
    print(f"入口頁衝突：{len(summary.index_conflicts)}")
    for title, values in (
        ("衝突", summary.conflicts),
        ("來源缺少", summary.missing),
        ("待同步", summary.pending),
    ):
        if values:
            print(f"\n{title}：")
            for value in values:
                print(f"- {value}")


def discover_manifest(start: Optional[Path] = None) -> Optional[Path]:
    """Find a manifest from cwd upward, preferring the project-root file."""

    current = (start or Path.cwd()).expanduser().resolve()
    if current.is_file():
        current = current.parent
    while True:
        for candidate in (
            current / MANIFEST_FILENAME,
            current / "research_docs" / MANIFEST_FILENAME,
        ):
            if candidate.is_file():
                return candidate.resolve()
        if current.parent == current:
            return None
        current = current.parent


def _manifest_argument(global_value: Optional[Path], sub_value: Optional[Path], *, start: Optional[Path] = None) -> Path:
    explicit = sub_value or global_value
    if explicit is not None:
        return Path(explicit).expanduser().resolve()
    discovered = discover_manifest(start)
    if discovered is None:
        raise ConfigError("找不到 manifest；請指定 --manifest 或在專案目錄建立 obsidian_sync_manifest.json")
    return discovered


def _safe_project_name(value: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ConfigError("project-name 必須是非空字串")
    if value in {".", ".."} or "/" in value or "\\" in value or "\n" in value or "\r" in value:
        raise ConfigError("project-name 不可含路徑分隔符或換行")
    return value


def init_manifest(
    project_root: Path,
    vault_root: Path,
    target_root: Path,
    project_name: str,
    *,
    manifest_path: Optional[Path] = None,
) -> Path:
    """Create a project-root manifest without writing anything in the vault."""

    project_root = Path(project_root).expanduser().resolve()
    if not project_root.is_dir():
        raise ConfigError(f"project-root 不存在或不是資料夾：{project_root}")
    project_name = _safe_project_name(project_name)
    vault_root = Path(vault_root).expanduser().resolve()
    target_root = Path(target_root).expanduser().resolve()
    if not vault_root.is_dir():
        raise ConfigError(f"vault-root 不存在或不是資料夾：{vault_root}")
    if not (vault_root / ".obsidian").is_dir():
        raise ConfigError(f"不是可確認的 Obsidian Vault（缺少 .obsidian）：{vault_root}")
    if not _inside(target_root, vault_root):
        raise ConfigError(f"同步目標不在指定 Vault 內：{target_root}")
    if target_root.exists() and not target_root.is_dir():
        raise ConfigError(f"target-root 存在但不是資料夾：{target_root}")

    maintenance_name = project_name + "_維護紀錄.md"
    todo_name = project_name + "_待辦事項.md"
    missing = [name for name in (maintenance_name, todo_name) if not (project_root / name).is_file()]
    if missing:
        raise ConfigError(
            "只有在專案根目錄已有維護紀錄與待辦事項時才能 init；缺少：" + ", ".join(missing)
        )

    destination = project_root / MANIFEST_FILENAME
    if manifest_path is not None:
        supplied = Path(manifest_path).expanduser().resolve()
        if supplied != destination:
            raise ConfigError(f"init 的 manifest 必須位於專案根目錄：{destination}")
    if destination.exists():
        raise ConfigError(f"manifest 已存在，為避免覆蓋而停止：{destination}")

    manifest: Dict[str, Any] = {
        "version": 1,
        "project_name": project_name,
        "vault_root": str(vault_root),
        "target_root": str(target_root),
        "roots": {"project": str(project_root)},
        "entries": [
            {
                "root": "project",
                "source": maintenance_name,
                "target": "05.維護與待辦/" + maintenance_name,
                "label": "維護紀錄",
                "category": "維護與待辦",
            },
            {
                "root": "project",
                "source": todo_name,
                "target": "05.維護與待辦/" + todo_name,
                "label": "待辦事項",
                "category": "維護與待辦",
            },
        ],
    }
    _atomic_write_json_if_changed(destination, manifest)
    return destination


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", dest="global_manifest", type=Path, default=None)
    parser.add_argument("--json", dest="global_json", action="store_true", help="輸出 JSON 摘要")
    subparsers = parser.add_subparsers(dest="command")

    init_parser = subparsers.add_parser("init", help="在專案根目錄建立 manifest")
    init_parser.add_argument("--manifest", dest="sub_manifest", type=Path, default=None)
    init_parser.add_argument("--json", dest="sub_json", action="store_true")
    init_parser.add_argument("--project-root", type=Path)
    init_parser.add_argument("--vault-root", type=Path)
    init_parser.add_argument("--target-root", type=Path)
    init_parser.add_argument("--project-name")

    for command, help_text in (("sync", "執行單向同步"), ("check", "只檢查，不寫入")):
        subparser = subparsers.add_parser(command, help=help_text)
        subparser.add_argument("--manifest", dest="sub_manifest", type=Path, default=None)
        subparser.add_argument("--json", dest="sub_json", action="store_true")
    return parser


def _emit_error(message: str, *, as_json: bool) -> None:
    if as_json:
        print(json.dumps({"error": message}, ensure_ascii=False))
    else:
        print(f"錯誤：{message}", file=sys.stderr)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = _build_parser()
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        # argparse's normal usage errors are configuration errors under this
        # CLI contract.  Preserve --help's successful status.
        return int(exc.code) if exc.code == 0 else 3

    as_json = bool(getattr(args, "global_json", False) or getattr(args, "sub_json", False))
    try:
        if args.command == "init":
            required = ("project_root", "vault_root", "target_root", "project_name")
            missing = [name for name in required if getattr(args, name, None) is None]
            if missing:
                raise ConfigError("init 缺少必要參數：" + ", ".join("--" + name.replace("_", "-") for name in missing))
            destination = init_manifest(
                args.project_root,
                args.vault_root,
                args.target_root,
                args.project_name,
                manifest_path=args.sub_manifest or args.global_manifest,
            )
            if as_json:
                print(json.dumps({"mode": "init", "manifest": str(destination)}, ensure_ascii=False))
            else:
                print(f"已建立 manifest：{destination}")
            return 0

        if args.command not in {"sync", "check"}:
            raise ConfigError("請指定 init、sync 或 check 子命令")
        manifest_path = _manifest_argument(args.global_manifest, args.sub_manifest)
        apply = args.command == "sync"
        summary = run_sync(manifest_path, apply=apply)
        _print_summary(summary, apply=apply, as_json=as_json)
        if summary.conflicts or summary.missing:
            return 2
        if not apply and (summary.pending or summary.index_pending):
            return 1
        return 0
    except (ConfigError, OSError, RuntimeError, ValueError) as exc:
        _emit_error(str(exc), as_json=as_json)
        return 3


if __name__ == "__main__":
    raise SystemExit(main())
